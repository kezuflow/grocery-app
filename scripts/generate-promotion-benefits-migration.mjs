import assert from "node:assert/strict";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";

// Generate from a frozen, in-memory 0084 baseline. Never open a retained database.
const directory = new URL("../apps/core/migrations/", import.meta.url);
const db = new DatabaseSync(":memory:");
db.exec("PRAGMA foreign_keys=ON");
for (const file of readdirSync(directory)
  .filter((name) => name.endsWith(".sql") && name < "0085")
  .sort()) {
  db.exec("BEGIN; PRAGMA defer_foreign_keys=ON;");
  db.exec(readFileSync(new URL(file, directory), "utf8"));
  db.exec("COMMIT");
}
const quote = (name) => `"${name.replaceAll('"', '""')}"`;
const objects = db
  .prepare(
    "SELECT type,name,tbl_name,sql FROM sqlite_schema WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY name",
  )
  .all();
const allTables = objects.filter((object) => object.type === "table");
const changed = new Set([
  "promotion",
  "promotion_grant",
  "promotion_redemption",
  "checkout_promotion_claim",
]);
const affected = new Set(changed);
let expanded = true;
while (expanded) {
  expanded = false;
  for (const table of allTables) {
    if (
      !affected.has(table.name) &&
      db
        .prepare(`PRAGMA foreign_key_list(${quote(table.name)})`)
        .all()
        .some((key) => affected.has(key.table))
    ) {
      affected.add(table.name);
      expanded = true;
    }
  }
}
assert.deepEqual([...affected].sort(), [
  "checkout_promotion_claim",
  "order_promotion_application",
  "promotion",
  "promotion_grant",
  "promotion_redemption",
  "promotion_rule",
]);
const tables = allTables.filter((table) => affected.has(table.name));
const output = [
  "-- Generated by scripts/generate-promotion-benefits-migration.mjs from the 0084 baseline.",
  "-- Preserve every affected row/rowid, index and historical snapshot. No database reset or storage calls.",
  "-- Legacy DELIVERY_FEE_DISCOUNT remains valid in historical evidence; live definitions use the explicit percentage type.",
  "PRAGMA defer_foreign_keys=ON;",
];
for (const table of tables)
  output.push(
    `CREATE TABLE ${quote(`schema_0085_${table.name}`)} AS SELECT rowid AS schema_original_rowid,* FROM ${quote(table.name)};`,
  );
const triggers = objects.filter(
  (object) => object.type === "trigger" && affected.has(object.tbl_name),
);
for (const trigger of triggers) output.push(`DROP TRIGGER ${quote(trigger.name)};`);
const remaining = new Set(affected);
while (remaining.size) {
  const next = [...remaining].find(
    (name) =>
      ![...remaining].some(
        (child) =>
          child !== name &&
          db
            .prepare(`PRAGMA foreign_key_list(${quote(child)})`)
            .all()
            .some((key) => key.table === name),
      ),
  );
  if (!next) throw new Error("Promotion schema has a foreign-key cycle");
  output.push(`DROP TABLE ${quote(next)};`);
  remaining.delete(next);
}
for (const table of tables) {
  const sql = changed.has(table.name)
    ? table.sql.replaceAll(
        "'DELIVERY_FEE_DISCOUNT'",
        "'DELIVERY_FEE_DISCOUNT','DELIVERY_PERCENT_DISCOUNT','DELIVERY_FIXED_DISCOUNT'",
      )
    : table.sql;
  output.push(`${sql};`);
}
for (const table of tables) {
  const columns = db
    .prepare(`PRAGMA table_info(${quote(table.name)})`)
    .all()
    .map((column) => column.name);
  output.push(
    `INSERT INTO ${quote(table.name)} (rowid,${columns.map(quote).join(",")}) SELECT schema_original_rowid,${columns.map(quote).join(",")} FROM ${quote(`schema_0085_${table.name}`)};`,
  );
}
for (const object of objects.filter(
  (object) => object.type === "index" && affected.has(object.tbl_name),
))
  output.push(`${object.sql};`);
for (const trigger of triggers) output.push(`${trigger.sql};`);
// Only uncommitted definition authority changes. Paid evidence retains its original vocabulary and JSON.
output.push(
  "UPDATE promotion SET benefit_type='DELIVERY_PERCENT_DISCOUNT',version=version+1 WHERE benefit_type='DELIVERY_FEE_DISCOUNT';",
);
for (const table of tables) output.push(`DROP TABLE ${quote(`schema_0085_${table.name}`)};`);
const sql = `${output.join("\n\n")}\n`;
const destination = new URL("0085_promotion_benefits.sql", directory);
if (process.argv.includes("--check"))
  assert.equal(readFileSync(destination, "utf8"), sql, "Regenerate promotion benefits migration");
else writeFileSync(destination, sql);
db.exec("BEGIN; PRAGMA defer_foreign_keys=ON;");
db.exec(sql);
db.exec("COMMIT");
assert.deepEqual(db.prepare("PRAGMA foreign_key_check").all(), []);
assert.equal(db.prepare("PRAGMA integrity_check").get().integrity_check, "ok");
console.log("Promotion benefits migration is reproducible and applies to a clean 0084 baseline.");
